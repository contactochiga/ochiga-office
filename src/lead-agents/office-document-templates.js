// Document templates (Phase 7, Office v2). Structural templates only —
// none of these fabricate business content; every section either comes
// from real input or shows an honest "add content" placeholder. The
// existing invoice/proposal-with-pricing shape (documentHtml in
// server.js) remains the "basic" template unchanged, reused here rather
// than duplicated, since it already covers that case correctly.
function escapeHtmlText(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));
}
function nl2br(value) {
  return escapeHtmlText(value).replace(/\n/g, "<br />");
}
function today() {
  return new Date().toLocaleDateString("en-NG", { day: "numeric", month: "long", year: "numeric" });
}

const SHARED_STYLE = `
  body{font-family:Arial,sans-serif;margin:0;background:#f4f7fb;color:#101828}
  .page{max-width:800px;margin:32px auto;background:white;border:1px solid #d8e0ea;border-radius:12px;overflow:hidden;padding:0}
  .brandbar{background:#06111f;color:white;padding:22px 34px;font-size:13px;letter-spacing:.16em;text-transform:uppercase;color:#60a5fa}
  .content{padding:34px}
  .content h1{font-size:26px;margin:0 0 4px;color:#101828}
  .content h2{font-size:16px;margin:26px 0 8px;color:#101828;border-bottom:1px solid #eef2f7;padding-bottom:6px}
  .meta-row{color:#667085;font-size:13px;margin-bottom:18px}
  .placeholder{color:#98a2b3;font-style:italic}
  .signature{margin-top:40px;border-top:1px solid #eef2f7;padding-top:16px;color:#667085;font-size:13px}
  .foot{padding:18px 34px;background:#f8fafc;color:#98a2b3;font-size:12px}
`;

function pageWrap(config, bodyHtml) {
  return `<!doctype html>
<html>
<head><meta charset="utf-8" /><style>${SHARED_STYLE}</style></head>
<body>
  <main class="page">
    <div class="brandbar">${escapeHtmlText(config.officeDocumentBrandName)}</div>
    <div class="content">${bodyHtml}</div>
    <div class="foot">Generated by Ochiga Office. Print this page to PDF or share the link directly.</div>
  </main>
</body>
</html>`;
}

function renderLetterhead(config, input) {
  return pageWrap(config, `
    <div class="meta-row">${today()}</div>
    <h1>${escapeHtmlText(input.title || "Letterhead")}</h1>
    <p>${input.body ? nl2br(input.body) : `<span class="placeholder">Add the letter content.</span>`}</p>
    <div class="signature">${escapeHtmlText(input.signature_name || "")}<br />${escapeHtmlText(input.signature_role || "")}</div>
  `);
}

function renderCoverLetter(config, input) {
  return pageWrap(config, `
    <div class="meta-row">${today()}</div>
    <p>${escapeHtmlText(input.recipient_name || "Recipient Name")}<br />${input.recipient_address ? nl2br(input.recipient_address) : ""}</p>
    <p>Dear ${escapeHtmlText(input.recipient_name || "Sir/Madam")},</p>
    <p>${input.body ? nl2br(input.body) : `<span class="placeholder">Add the letter content.</span>`}</p>
    <p>Yours sincerely,</p>
    <div class="signature">${escapeHtmlText(input.signature_name || "")}<br />${escapeHtmlText(input.signature_role || "")}</div>
  `);
}

function renderMemo(config, input) {
  return pageWrap(config, `
    <h1>Memorandum</h1>
    <table style="width:100%;font-size:13px;color:#101828;margin:14px 0 22px;">
      <tr><td style="width:80px;color:#667085;">To</td><td>${escapeHtmlText(input.memo_to || "")}</td></tr>
      <tr><td style="color:#667085;">From</td><td>${escapeHtmlText(input.memo_from || "")}</td></tr>
      <tr><td style="color:#667085;">Date</td><td>${today()}</td></tr>
      <tr><td style="color:#667085;">Re</td><td>${escapeHtmlText(input.title || "")}</td></tr>
    </table>
    <p>${input.body ? nl2br(input.body) : `<span class="placeholder">Add the memo content.</span>`}</p>
  `);
}

// Structure matches docs/commercial/PROPOSAL_TEMPLATE_V1.md's real
// section outline. input.sections is an optional {key: text} map;
// missing sections render an honest placeholder, never fabricated copy.
const PROPOSAL_SECTIONS = [
  ["executive_summary", "Executive Summary"],
  ["current_challenges", "Current Challenges"],
  ["recommended_package", "Recommended Oyi Package"],
  ["building_review_findings", "Building Review Findings"],
  ["deployment_scope", "Deployment Scope"],
  ["integration_scope", "Integration Scope"],
  ["intelligence_scope", "Intelligence Scope"],
  ["timeline", "Timeline"],
  ["commercials", "Commercials"],
  ["acceptance", "Acceptance"],
];
function renderProposal(config, input) {
  const sections = input.sections && typeof input.sections === "object" ? input.sections : {};
  const sectionsHtml = PROPOSAL_SECTIONS.map(
    ([key, label]) => `<h2>${escapeHtmlText(label)}</h2><p>${sections[key] ? nl2br(sections[key]) : `<span class="placeholder">Add content for this section.</span>`}</p>`
  ).join("");
  return pageWrap(config, `
    <div class="meta-row">Prepared for ${escapeHtmlText(input.recipient || "Client")} · ${today()}</div>
    <h1>${escapeHtmlText(input.title || "Oyi Deployment Proposal")}</h1>
    ${sectionsHtml}
  `);
}

const TEMPLATES = {
  letterhead: { id: "letterhead", label: "Ochiga Letterhead", description: "Branded letterhead for general correspondence.", render: renderLetterhead },
  cover_letter: { id: "cover_letter", label: "Cover Letter", description: "Standard business cover letter.", render: renderCoverLetter },
  memo: { id: "memo", label: "Memo", description: "Internal memo (To/From/Date/Re).", render: renderMemo },
  proposal: { id: "proposal", label: "Proposal", description: "Structured Oyi deployment proposal, matching the existing proposal outline.", render: renderProposal },
  // "basic" is handled by the caller falling back to the existing
  // documentHtml() in server.js — listed here only so it appears in the
  // template picker with the same shape as the others.
  basic: { id: "basic", label: "Basic Corporate Document", description: "General document with recipient, status, and amount — the existing default." },
};

function listDocumentTemplates() {
  return Object.values(TEMPLATES).map(({ id, label, description }) => ({ id, label, description }));
}

function renderDocumentFromTemplate(templateId, config, input) {
  const template = TEMPLATES[templateId];
  if (!template || !template.render) return null;
  return template.render(config, input);
}

module.exports = { listDocumentTemplates, renderDocumentFromTemplate };
